
"""HTML 폼과 Supabase PostgreSQL로 만드는 작은 방명록."""

import json
import os
from contextlib import asynccontextmanager
from datetime import datetime, timezone
from html import escape
from pathlib import Path
from urllib.parse import parse_qs

import psycopg
from psycopg.rows import dict_row

from fastapi import FastAPI, Query, Request
from fastapi.concurrency import run_in_threadpool
from fastapi.responses import HTMLResponse, RedirectResponse
from pydantic import BaseModel, ConfigDict, Field, ValidationError


BASE_DIR = Path(__file__).resolve().parent
CONFIG_PATH = BASE_DIR / "config.json"

PAGE_SIZE = 20
MAX_ENTRIES = 1000
MAX_BODY_BYTES = 16384

TEMPLATE = (
    BASE_DIR / "templates" / "index.html"
).read_text(encoding="utf-8")


# --------------------------------------------------
# 1. Supabase 설정 읽기
# --------------------------------------------------

def load_config(config_path: Path = CONFIG_PATH) -> dict:
    """
    Render에서는 환경변수로 DB 접속 정보를 읽고,
    로컬에서는 config.json을 사용합니다.
    """

    env_names = {
        "host": "DB_HOST",
        "port": "DB_PORT",
        "dbname": "DB_NAME",
        "user": "DB_USER",
        "password": "DB_PASSWORD",
    }

    is_render = os.getenv("RENDER", "").lower() == "true"
    has_db_env = any(
        os.getenv(name) is not None
        for name in env_names.values()
    )

    if is_render or has_db_env:
        missing = [
            env_name
            for env_name in env_names.values()
            if not os.getenv(env_name, "").strip()
        ]

        if missing:
            raise ValueError(
                "필수 데이터베이스 환경변수가 누락되었습니다: "
                + ", ".join(missing)
            )

        config = {
            key: os.environ[env_name]
            for key, env_name in env_names.items()
        }

    else:
        # 로컬 개발 환경에서만 config.json 사용
        if not config_path.is_file():
            raise FileNotFoundError(
                f"설정 파일을 찾을 수 없습니다: {config_path}"
            )

        with config_path.open("r", encoding="utf-8") as file:
            config = json.load(file)

    required = ("host", "port", "dbname", "user", "password")

    if any(
        key not in config
        or config[key] is None
        or not str(config[key]).strip()
        for key in required
    ):
        raise ValueError(
            "DB 접속 정보에 host, port, dbname, user, password가 "
            "모두 필요합니다."
        )

    try:
        port = int(config["port"])
    except (TypeError, ValueError) as exc:
        raise ValueError("DB 포트는 정수여야 합니다.") from exc

    if not 1 <= port <= 65535:
        raise ValueError("DB 포트는 1~65535 범위여야 합니다.")

    return {
        "host": str(config["host"]).strip(),
        "port": port,
        "dbname": str(config["dbname"]).strip(),
        "user": str(config["user"]).strip(),
        "password": str(config["password"]),
        "sslmode": "require",
        "connect_timeout": 10,
        "row_factory": dict_row,
    }


# --------------------------------------------------
# 2. 데이터베이스 연결
# --------------------------------------------------

def connect(db_config: dict):
    """Supabase PostgreSQL 연결을 생성합니다."""

    return psycopg.connect(**db_config)


# --------------------------------------------------
# 3. 테이블 생성
# --------------------------------------------------

def init_db(db_config: dict):
    """entries 테이블이 없으면 생성합니다."""

    with connect(db_config) as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS public.entries (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(30) NOT NULL
                    CHECK (char_length(name) BETWEEN 1 AND 30),
                message VARCHAR(1000) NOT NULL
                    CHECK (char_length(message) BETWEEN 1 AND 1000),
                created_at TIMESTAMPTZ NOT NULL
            )
        """)


# --------------------------------------------------
# 4. 방명록 목록 조회 및 HTML 렌더링
# --------------------------------------------------

def render_page(
    db_config: dict,
    page: int = 1,
    error: str = "",
    name: str = "",
    message: str = "",
    status: int = 200,
):
    with connect(db_config) as connection:
        total = connection.execute("""
            SELECT COUNT(*) AS total
            FROM public.entries
        """).fetchone()["total"]

        last_page = max(
            1,
            (total + PAGE_SIZE - 1) // PAGE_SIZE
        )

        page = min(page, last_page)

        records = connection.execute(
            """
            SELECT id, name, message, created_at
            FROM public.entries
            ORDER BY id DESC
            LIMIT %s OFFSET %s
            """,
            (PAGE_SIZE, (page - 1) * PAGE_SIZE),
        ).fetchall()

    cards = []

    for record in records:
        created_at = record["created_at"].isoformat(
            timespec="seconds"
        )

        display_time = (
            created_at
            .replace("T", " ")
            .replace("+00:00", " UTC")
        )

        cards.append(
            '<article class="entry"><header>'
            f'<strong>{escape(record["name"])}</strong>'
            f'<time datetime="{escape(created_at)}">'
            f'{escape(display_time)}'
            '</time></header>'
            f'<p class="message">'
            f'{escape(record["message"])}</p></article>'
        )

    if not cards:
        cards.append(
            '<p class="empty">'
            '아직 남겨진 인사가 없어요. '
            '첫 번째 인사를 남겨 주세요.'
            '</p>'
        )

    navigation = []

    if page > 1:
        navigation.append(
            f'<a href="/?page={page - 1}">← 이전</a>'
        )

    navigation.append(
        f'<span>{page} / {last_page}</span>'
    )

    if page < last_page:
        navigation.append(
            f'<a href="/?page={page + 1}">다음 →</a>'
        )

    values = {
        "total": str(total),
        "error": (
            f'<p class="error" role="alert">'
            f'{escape(error)}</p>'
            if error else ""
        ),
        "name": escape(name, quote=True),
        "message": escape(message),
        "entries": "".join(cards),
        "navigation": "".join(navigation),
    }

    # 사용자 입력값에 포함된 @@가 다시 치환되지 않도록 처리합니다.
    parts = TEMPLATE.split("@@")

    html = "".join(
        values.get(part, part) if i % 2 else part
        for i, part in enumerate(parts)
    )

    return HTMLResponse(html, status_code=status)


# --------------------------------------------------
# 5. 입력 데이터 검증
# --------------------------------------------------

class EntryInput(BaseModel):
    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
    )

    name: str = Field(min_length=1, max_length=30)
    message: str = Field(min_length=1, max_length=1000)


# --------------------------------------------------
# 6. 방명록 저장
# --------------------------------------------------

def save_entry(db_config: dict, entry: EntryInput) -> bool:
    """글 수 제한을 확인하고 방명록을 저장합니다."""

    with connect(db_config) as connection:
        # 동시에 여러 글이 저장될 때 글 수 제한을 초과하지 않도록
        # 테이블 쓰기 작업을 직렬화합니다.
        connection.execute(
            "LOCK TABLE public.entries IN EXCLUSIVE MODE"
        )

        total = connection.execute("""
            SELECT COUNT(*) AS total
            FROM public.entries
        """).fetchone()["total"]

        if total >= MAX_ENTRIES:
            return False

        connection.execute(
            """
            INSERT INTO public.entries
                (name, message, created_at)
            VALUES (%s, %s, %s)
            """,
            (
                entry.name,
                entry.message,
                datetime.now(timezone.utc),
            ),
        )

    # 정상 종료 시 트랜잭션이 커밋됩니다.
    return True


# --------------------------------------------------
# 7. 폼 데이터 처리
# --------------------------------------------------

def submit_entry(db_config: dict, body: bytes):
    name, message = "", ""

    try:
        fields = parse_qs(
            body.decode("utf-8"),
            keep_blank_values=True,
            max_num_fields=2,
            errors="strict",
        )

        if (
            set(fields) != {"name", "message"}
            or any(len(v) != 1 for v in fields.values())
        ):
            raise ValueError("잘못된 폼")

        name = fields["name"][0]
        message = fields["message"][0]

        entry = EntryInput(
            name=name,
            message=message,
        )

    except (ValueError, UnicodeDecodeError, ValidationError):
        return render_page(
            db_config,
            error=(
                "이름은 1~30자, 내용은 1~1,000자로 "
                "입력해 주세요. 공백만 입력할 수 없습니다."
            ),
            name=name,
            message=message,
            status=422,
        )

    if not save_entry(db_config, entry):
        return render_page(
            db_config,
            error=(
                "방명록이 가득 찼습니다. "
                "지금은 새 글을 받을 수 없습니다."
            ),
            name=name,
            message=message,
            status=409,
        )

    # POST 후 GET으로 이동하여 중복 제출을 방지합니다.
    return RedirectResponse("/", status_code=303)


# --------------------------------------------------
# 8. FastAPI 애플리케이션 생성
# --------------------------------------------------

def create_app(config_path: Path | None = None):
    path = (
        Path(config_path)
        if config_path is not None
        else CONFIG_PATH
    )

    db_config = load_config(path)

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        await run_in_threadpool(init_db, db_config)
        yield

    application = FastAPI(
        title="작은 방명록",
        lifespan=lifespan,
        docs_url=None,
        redoc_url=None,
    )

    # 보안 헤더
    @application.middleware("http")
    async def response_headers(request: Request, call_next):
        response = await call_next(request)

        response.headers["Content-Security-Policy"] = (
            "default-src 'none'; style-src 'unsafe-inline'; "
            "form-action 'self'; frame-ancestors 'none'; "
            "base-uri 'none'"
        )
        response.headers["X-Content-Type-Options"] = "nosniff"
        response.headers["Cache-Control"] = "no-store"

        return response

    # PostgreSQL 오류 처리
    @application.exception_handler(psycopg.Error)
    async def database_error(request: Request, error: psycopg.Error):
        return HTMLResponse(
            '<!doctype html><html lang="ko">'
            '<meta charset="utf-8">'
            '<title>잠시 후 다시 시도해 주세요</title>'
            '<h1>저장소에 연결할 수 없습니다.</h1>'
            '<p>잠시 후 다시 시도해 주세요.</p>'
            '<a href="/">방명록으로 돌아가기</a></html>',
            status_code=503,
        )

    # 메인 페이지
    @application.get("/", response_class=HTMLResponse)
    def home(
        page: int = Query(default=1, ge=1, le=1000000)
    ):
        return render_page(db_config, page=page)

    # 방명록 작성
    @application.post("/entries")
    async def create_entry(request: Request):
        if request.headers.get("sec-fetch-site") == "cross-site":
            return HTMLResponse(
                "다른 사이트에서는 글을 작성할 수 없습니다.",
                status_code=403,
            )

        content_type = (
            request.headers.get("content-type", "")
            .split(";")[0]
            .strip()
            .lower()
        )

        if content_type != "application/x-www-form-urlencoded":
            return HTMLResponse(
                "HTML 폼으로 작성해 주세요.",
                status_code=415,
            )

        body = bytearray()

        async for chunk in request.stream():
            body.extend(chunk)

            if len(body) > MAX_BODY_BYTES:
                return HTMLResponse(
                    "입력한 내용이 너무 큽니다.",
                    status_code=413,
                )

        return await run_in_threadpool(
            submit_entry,
            db_config,
            bytes(body),
        )

    # 데이터베이스 연결 상태 확인
    @application.get("/health")
    def health():
        with connect(db_config) as connection:
            connection.execute(
                "SELECT id FROM public.entries LIMIT 1"
            ).fetchone()

        return {"status": "ok"}

    return application


app = create_app()